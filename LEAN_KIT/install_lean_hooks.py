def _shape(path):
    """"windows", "posix" or None — which machine a path is spelled for."""
    p = str(path or "")
    if re.match(r"^[A-Za-z]:[\\/]", p) or p.startswith("\\\\"):
        return "windows"
    if p.startswith("/"):
        return "posix"
    return None


def refuse_wrong_machine(python_exe, project_dir):
    """A settings.json is a set of paths for ONE machine. Refuse to mix them.

    FOUND IN LIVE USE, 2026-09-09. This installer was run from a Linux sandbox, where
    `sys.executable` is `/usr/bin/python3` and the project is reached at `/sessions/.../mnt/...`.
    Both defaults were taken, and BOTH PROJECTS' `.claude/settings.json` were rewritten with
    paths that do not exist on the client's machine. SessionStart, the PreToolUse guard and the
    SubagentStop handback could not fire at all, and **nothing said so** — the heartbeat sat
    frozen for 3898 seconds while commands ran.
    ``--status`` could not catch it either: it asks whether the interpreter exists HERE, and
    `/usr/bin/python3` exists perfectly well where the damage was done.
    So the test is not "does this path exist" — it is "is this path spelled for the same machine
    as the project", which is answerable from anywhere.
    """
    want = _shape(project_dir)
    got = _shape(python_exe)
    if want and got and want != got:
        sys.exit(
            "REFUSED — this would install %s paths into a %s project.\n"
            "    project     : %s\n"
            "    interpreter : %s\n"
            "\n"
            "  Hooks are launched by the machine that OWNS the project, so an interpreter path\n"
            "  from anywhere else can never run. Installing it does not fail loudly: the hooks\n"
            "  sit in settings.json looking installed and simply never fire.\n"
            "\n"
            "  Run the installer on the project's own machine, or pass its interpreter:\n"
            "      --python \"C:\\Users\\<you>\\AppData\\Local\\Programs\\Python\\Python312\\python.exe\""
            % (got, want, project_dir, python_exe))


def settings_for(python_exe, project_dir):
    r"""The hooks, wired to an ABSOLUTE interpreter and THE MASTER'S hook files.

    CHANGED 2026-09-14 ON THE CLIENT'S ORDER: *"I don't want the kit running on it's own copy of the
    lean kit. Ever. It should be forced to run off of the controls in the lean_kit folder and it
    should not be able to edit anything that controls it's processes."*

    These used to name `<project>\.claude\hooks\guard.py` — a COPY, installed into the project,
    and therefore INSIDE the boundary that `guard.py` itself enforces. That is the hole: the
    guard's strongest rule is *writes are allowed inside the project and nowhere else*, and a copy
    of the guard inside the project is on the permitted side of its own rule. Only the
    by-name list stood in front of it.

    Pointing settings.json at `LEAN_KIT\hooks\` fixes it for free and by construction:
    the hook files are now OUTSIDE every project, so **the boundary rule the guard already
    enforces is what protects the guard.** One copy, edited only by the client, and a session cannot reach
    it without tripping the refusal that was already written.
    """
    def cmd(name):
        return '"%s" "%s"' % (python_exe, os.path.join(HOOKS_SRC, name))
    refuse_wrong_machine(python_exe, project_dir)
    refuse_wrong_machine(python_exe, HOOKS_SRC)
    _kit = os.path.join(HERE, "kit")
    return {
        "env": {
            "KIT_HOME": _kit,
            "PYTHONPATH": _kit,
            "PYTHONUTF8": "1",
            "PYTHONIOENCODING": "utf-8",
        },
        "hooks": {
            "SessionStart": [
                {"matcher": "",
                 "hooks": [{"type": "command", "command": cmd("session_start.py")}]}
            ],
            "PreToolUse": [
                {"matcher": "Bash|Write|Edit|MultiEdit|Read|Task|Agent",
                 "hooks": [{"type": "command", "command": cmd("guard.py")}]}
            ],
            "PostToolUse": [
                {"matcher": "Bash|Task|Agent",
                 "hooks": [{"type": "command", "command": cmd("wallclock.py")}]}
            ],
            "SubagentStop": [
                {"matcher": "",
                 "hooks": [{"type": "command", "command": cmd("handback.py")}]}
            ],
            "Stop": [
                {"matcher": "",
                 "hooks": [{"type": "command", "command": cmd("stop_guard.py")}]}
            ],
        }
    }


def status(project):
    p = os.path.join(project, ".claude", "settings.json")
    if not os.path.exists(p):
        print("NOT INSTALLED — no %s" % p)
        return 1
    try:
        with open(p, encoding="utf-8") as fh:
            cfg = json.load(fh)
    except Exception as exc:
        print("UNREADABLE %s (%s)" % (p, exc))
        return 1
    bad, foreign = 0, 0
    win_here = (os.name == "nt")
    print("wired in %s:" % p)
    for event, entries in (cfg.get("hooks") or {}).items():
        for e in entries:
            for h in e.get("hooks") or []:
                c = str(h.get("command", ""))
                exe = c.split('"')[1] if c.startswith('"') else c.split()[0] if c else ""
                _parts = [x for x in c.split('"') if x.strip()]; scr = _parts[1] if len(_parts) > 1 else ""
                looks_windows = bool(re.match(r"^[A-Za-z]:[\\/]", exe))
                if looks_windows and not win_here:
                    foreign += 1
                    verdict = "<-- Windows path; cannot be checked from here"
                    ok = None
                else:
                    ok = os.path.isabs(exe) and os.path.exists(exe)
                    verdict = "OK" if ok else "<-- INTERPRETER NOT FOUND"
                    if ok and scr and not os.path.exists(scr):
                        ok = False; verdict = "<-- HOOK SCRIPT NOT FOUND: %s" % scr
                    if not ok:
                        bad += 1
                print("  %-14s %s   %s" % (event, c, verdict))
    if bad:
        print("\n%d hook(s) name an interpreter or a hook script this machine cannot run. They are NOT firing, "
              "and nothing\nwill say so at the moment they fail to. Re-run this installer with "
              "the Python you intend to keep (from the kit's own folder)." % bad)
        return 1
    if foreign:
        print("\n%d hook(s) name a WINDOWS interpreter and this is not Windows, so their "
              "existence cannot be\nchecked from here. That is not a failure — it is the wrong "
              "machine to ask. Re-run this with\n--status in a Windows shell to get a real "
              "answer. Nothing has been changed." % foreign)
        return 0
    print("\nAll hooks name an interpreter that exists on this machine.")
    return 0


