def _projects_read():
    try:
        with open(PROJECTS, encoding="utf-8") as fh:
            d = json.load(fh)
        return [p for p in (d.get("projects") or []) if isinstance(p, str) and p.strip()]
    except Exception:
        return []


def _projects_add(project):
    """record a project in the machine's list (once; the path as given, absolute); False when the list cannot be written"""
    ps = _projects_read(); key = os.path.normcase(os.path.abspath(project))
    ps = [p for p in ps if os.path.normcase(os.path.abspath(p)) != key] + [os.path.abspath(project)]
    try:
        os.makedirs(os.path.dirname(PROJECTS), exist_ok=True)
        with open(PROJECTS, "w", encoding="utf-8") as fh:
            json.dump({"projects": sorted(ps, key=lambda p: p.lower()), "when": time.strftime("%Y-%m-%d %H:%M:%S"), "kit": HERE}, fh, indent=1)
        return True
    except Exception:
        return False


