def _psline(py, script, *args, **kw):
    """One pastable PowerShell line. `leangate.psline` is the OWNER; this only borrows it.

    Rule 0 of LEAN_KIT: one owner per fact. The `&` call operator and the never-say-`python`
    rule are facts about the client's shell, they live in `leangate.py`, and this installer asks rather
    than restating them. The fallback exists only so an installer run can never die for want of
    the kit module — and it is the same spelling, which is checked by `selftest_psline.py`.
    """
    try:
        sys.path.insert(0, os.path.join(HERE, "kit"))
        import leangate
        return leangate.psline(script, *args, py=py, **kw)
    except Exception:
        parts = ['&', '"%s"' % py, '"%s"' % script] + \
                [(a if re.match(r"^-{1,2}[A-Za-z0-9][\w-]*$", str(a)) else '"%s"' % a)
                 for a in args]
        line = " ".join(parts)
        return ('cd "%s"; %s' % (kw["cwd"], line)) if kw.get("cwd") else line


